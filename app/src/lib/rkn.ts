// Черновик уведомления в Роскомнадзор для автосервиса (раздел 6.3, п. 7 плана; Л2 проверки 4 октября).
// Оператор данных клиентов — сам автосервис, подаёт он: Госуслуги («Уведомление об обработке персональных данных»)
// или pd.rkn.gov.ru. Здесь — готовые ответы на поля формы. Это черновик: сверить с формой и показать юристу.
import { RETENTION_YEARS, type Processor } from "./legal";
import { formatPhone } from "./phone";

type Biz = { name: string; operatorName: string | null; operatorInn: string | null; address: string; city: string; phone: string };

/** Где стоит база данных: город и хостинг-провайдер из .env (DB_LOCATION). */
export const dbLocation = () => process.env.DB_LOCATION?.trim() || "Российская Федерация [укажите город и хостинг-провайдера]";

export function rknDraft(b: Biz, pr: Processor, startDate: string): string {
  const op = b.operatorName || b.name;
  return [
    `Черновик уведомления в Роскомнадзор об обработке персональных данных — ${b.name}`,
    "Подать: Госуслуги → «Уведомление об обработке персональных данных» или pd.rkn.gov.ru → «Уведомление об обработке ПДн». Подать нужно до начала онлайн-записи.",
    "",
    `1. Оператор: ${op}${b.operatorInn ? `, ИНН ${b.operatorInn}` : ""}. Адрес: ${b.city}, ${b.address}. Телефон: ${formatPhone(b.phone)}.`,
    "2. Цель обработки: запись клиентов на услуги по обслуживанию и ремонту автомобилей, связь с клиентом по поводу записи, хранение истории обращений для рассмотрения претензий по качеству работ.",
    "3. Категории персональных данных: фамилия, имя, отчество (указывается только имя); номер телефона. Иные: марка и модель автомобиля, комментарий к записи, дата, время и услуга записи, IP-адрес и время дачи согласия.",
    "4. Категории субъектов: клиенты — физические лица, записывающиеся на услуги.",
    "5. Правовое основание: п. 1 ч. 1 ст. 6 Федерального закона № 152-ФЗ (согласие субъекта, отдельный документ при записи на сайте); п. 5 ч. 1 ст. 6 (договор с клиентом) — для записей, внесённых по телефону.",
    "6. Действия с данными: сбор, запись, систематизация, накопление, хранение, уточнение, извлечение, использование, удаление, уничтожение.",
    "7. Способ обработки: автоматизированная, с передачей по сети Интернет (защищённое соединение HTTPS).",
    "8. Меры защиты (ст. 18.1 и 19 152-ФЗ): назначен ответственный за обработку; опубликованы политика обработки и текст согласия на сайте; доступ к данным только по паролю владельца; ограничение числа попыток входа; шифрование при передаче (TLS); резервное копирование; журнал действий; хранение на серверах в России.",
    "9. Шифровальные (криптографические) средства: не используются. Сертифицированные СКЗИ не применяются; данные передаются по защищённому протоколу HTTPS (в форме выбрать «не используются»: класс СКЗИ указывается только для сертифицированных средств).",
    `10. Обработку по поручению оператора ведёт: ${pr.name}, ИНН ${pr.inn} (сервис онлайн-записи «Автослот»).`,
    "11. Трансграничная передача: не осуществляется.",
    `12. Место нахождения базы данных: ${dbLocation()}.`,
    `13. Дата начала обработки: ${startDate}.`,
    `14. Срок или условие прекращения: ${RETENTION_YEARS} года с даты записи клиента или отзыв согласия; прекращение деятельности оператора.`,
    `15. Ответственный за организацию обработки: ${op}, телефон ${formatPhone(b.phone)}. Для ООО укажите конкретного сотрудника (обычно директора), назначенного приказом.`,
  ].join("\n");
}
