export const CONSENT_TITLE = "Согласие на обработку персональных данных";
export const PRIVACY_TITLE = "Политика обработки персональных данных";
export const RETENTION_YEARS = 3;

export type LegalParty = { name: string; inn: string | null; address: string; phone: string };
export type Processor = { name: string; inn: string; email: string };

export function processor(): Processor {
  return {
    name: process.env.PROCESSOR_NAME || "самозанятый (реквизиты не заполнены)",
    inn: process.env.PROCESSOR_INN || "не указан",
    email: process.env.PROCESSOR_EMAIL || "не указан",
  };
}

