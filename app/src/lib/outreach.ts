/** Номер варианта первого сообщения по адресу демо. */
export const questionVariant = (slug: string) => hash(`q:${slug}`) % QUESTIONS.length;

/** Первое сообщение. variant — номер варианта (для проверки); по умолчанию выбирается по адресу демо. */
export function question(b: Biz, opts: { now?: number; variant?: number } = {}) {
  const { where, facts } = card(b);
  return QUESTIONS[opts.variant ?? questionVariant(b.slug ?? b.name)].text({ where, facts, season: season(b, opts.now) });
}

